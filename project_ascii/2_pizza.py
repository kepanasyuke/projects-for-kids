"""Задание 2: множество и пицца."""

from common import clear_screen, pause, require_student_work, title


# ============================================================
# НАЧАЛО КОДА УЧЕНИКА
# Запиши 4 ингредиента между фигурными скобками.
# Повтор можно оставить: set сохранит продукт только один раз.
# Пример: PIZZA_INGREDIENTS = {"сыр", "томаты", "сыр", "оливки"}
PIZZA_INGREDIENTS = {
    "ВПИШИ_ПРОДУКТ_1",
    "ВПИШИ_ПРОДУКТ_2",
    "ВПИШИ_ПРОДУКТ_3",
    "ВПИШИ_ПРОДУКТ_4",
}
# КОНЕЦ КОДА УЧЕНИКА
# ============================================================


def pizza_program() -> None:
    if not require_student_work(
        PIZZA_INGREDIENTS,
        {
            "ВПИШИ_ПРОДУКТ_1",
            "ВПИШИ_ПРОДУКТ_2",
            "ВПИШИ_ПРОДУКТ_3",
            "ВПИШИ_ПРОДУКТ_4",
        },
        "2 — множество",
        '{"сыр", "томаты", "сыр", "оливки"}',
    ):
        return
    frames = [
        ["      .------.      ", "    .'  🍅  🧀 '.    ", "   /  🌶️  🫑  🧄  \\", "  '______________'  "],
        ["      .------.      ", "    .'  🧀  🍅 '.    ", "   /  🧄  🌶️  🫑  \\", "  '______________'  "],
        ["      .------.      ", "    .'  🫑  🧄 '.    ", "   /  🍅  🧀  🌶️  \\", "  '______________'  "],
    ]
    title("🍕  ПИЦЦЕРИЯ: МНОЖЕСТВО  🍕")
    print("\nМножество оставляет только уникальные ингредиенты. Печь включается!\n")
    pause(0.7)
    for frame_number in range(9):
        clear_screen()
        title("🍕  ПИЦЦА ВРАЩАЕТСЯ  🍕")
        print("\n🔥 Печь разогревается...\n")
        print("\n".join(frames[frame_number % len(frames)]))
        print("\n                 ✨  🔥  ✨")
        print(f"\nВращение: {frame_number + 1}/9")
        pause(0.18)
    clear_screen()
    title("🍕  ПИЦЦА ГОТОВА!  🍕")
    print("\nИнгредиенты добавляются по одному:\n")
    for ingredient in sorted(PIZZA_INGREDIENTS):
        print(f"  + {ingredient}")
        pause(0.25)
    print(f"\n✅ Уникальных ингредиентов: {len(PIZZA_INGREDIENTS)}")


if __name__ == "__main__":
    pizza_program()

"""Задание 4: словарь и ASCII-герой."""

import common


# ============================================================
# НАЧАЛО КОДА УЧЕНИКА
# Измени значения справа от ключей или добавь новую характеристику.
# Пример: "костюм": "Плащ-невидимка"
HERO = {
    "имя": "ВПИШИ_ИМЯ",
    "волосы": "ВПИШИ_ПРИЧЕСКУ",
    "сила": "ВПИШИ_СУПЕРСИЛУ",
    "оружие": "ВПИШИ_ОРУЖИЕ",
}
# КОНЕЦ КОДА УЧЕНИКА
# ============================================================

TEMPLATE = {"имя": "ВПИШИ_ИМЯ", "волосы": "ВПИШИ_ПРИЧЕСКУ", "сила": "ВПИШИ_СУПЕРСИЛУ", "оружие": "ВПИШИ_ОРУЖИЕ"}


def hero_program() -> None:
    if HERO == TEMPLATE or any(value.startswith("ВПИШИ_") for value in HERO.values()):
        common.clear_screen()
        common.title("GAME OVER: СОЗДАЙ ГЕРОЯ")
        print('\nЗамени значения в блоке КОДА УЧЕНИКА файла 4_hero.py.')
        print('Пример: "сила": "Полёт", "оружие": "Меч-молния"')
        return
    for part, value in HERO.items():
        common.clear_screen()
        common.title("ASCII-ГЕРОЙ · СЛОВАРЬ")
        print("\n" * 2 + " " * 20 + "  O  \n" + " " * 19 + " /|\\ \n" + " " * 19 + " / \\ ")
        print(f"\n✨ {part}: {value} ✨")
        common.pause(0.5)
    print("\n✅ Герой создан: словарь хранит характеристики по ключам.")


if __name__ == "__main__":
    hero_program()
